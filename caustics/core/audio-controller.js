export function initAudio(app) {
    if (!window.audioManager) return;

    // When song ends naturally, play a random track from the entire collection
    window.audioManager.audio.onended = () => nextBGM(app, true, false);
    
    // Initial load: pick a random track without auto-playing immediately
    nextBGM(app, false, false);
}

export function nextBGM(app, autoPlay = true, manualSequential = false) {
    if (!window.audioManager) return;

    let selectedTrack;
    const currentTrackUrl = window.audioManager.currentTrack || "";
    const currentTrackFilename = currentTrackUrl.replace(BGM_BASE_PATH, "");

    if (manualSequential && currentTrackFilename) {
        // Find current genre (prefix before /)
        const genre = currentTrackFilename.split('/')[0];
        const genreTracks = BGM_TRACKS.filter(t => t.startsWith(genre + '/'));
        
        if (genreTracks.length > 0) {
            const currentIndex = genreTracks.indexOf(currentTrackFilename);
            const nextIndex = (currentIndex + 1) % genreTracks.length;
            selectedTrack = genreTracks[nextIndex];
        } else {
            // Fallback to global random if genre not found
            selectedTrack = BGM_TRACKS[Math.floor(Math.random() * BGM_TRACKS.length)];
        }
    } else {
        // Pick a random track from the global list
        // Try not to repeat the same track if possible
        const candidates = BGM_TRACKS.filter(t => t !== currentTrackFilename);
        const pool = candidates.length > 0 ? candidates : BGM_TRACKS;
        selectedTrack = pool[Math.floor(Math.random() * pool.length)];
    }

    if (!selectedTrack) return;

    app.currentTrackName = selectedTrack.split('/').pop().replace('.mp3', '').replace(/_/g, ' ');

    const url = BGM_BASE_PATH + selectedTrack;
    if (autoPlay) {
        window.audioManager.play(url, { forceSwitch: true });
    } else {
        window.audioManager.currentTrack = url;
        window.audioManager.audio.src = url;
    }
}

export function formatTime(seconds) {
    const mins = Math.floor(seconds / 60);
    const secs = Math.floor(seconds % 60);
    const ms = Math.floor((seconds % 1) * 100);
    return `${mins.toString().padStart(2, '0')}:${secs.toString().padStart(2, '0')}.${ms.toString().padStart(2, '0')}`;
}
